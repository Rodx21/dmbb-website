-- ================================================================
-- VIEW: top scorers by division
-- ================================================================
CREATE OR REPLACE VIEW top_scorers_by_division AS
SELECT
  p.id                          AS player_id,
  p.name                        AS player_name,
  p.number                      AS jersey_number,
  t.id                          AS team_id,
  t.name                        AS team_name,
  t.short_name                  AS team_short,
  d.id                          AS division_id,
  d.name                        AS division_name,
  COUNT(ps.fixture_id)          AS games_played,
  SUM(ps.points)                AS total_points,
  ROUND(AVG(ps.points)::numeric, 1) AS avg_points
FROM player_stats ps
JOIN players   p ON p.id = ps.player_id
JOIN teams     t ON t.id = ps.team_id
JOIN fixtures  f ON f.id = ps.fixture_id
JOIN divisions d ON d.id = f.division_id
WHERE f.status = 'finished'
GROUP BY p.id, p.name, p.number, t.id, t.name, t.short_name, d.id, d.name
ORDER BY avg_points DESC;

GRANT SELECT ON top_scorers_by_division TO anon, authenticated;

