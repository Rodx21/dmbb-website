-- ----------------------------------------------------------------
-- TABLES
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS players (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  team_id    uuid REFERENCES teams(id) ON DELETE CASCADE NOT NULL,
  name       text NOT NULL,
  number     int,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS player_stats (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fixture_id text REFERENCES fixtures(id) ON DELETE CASCADE NOT NULL,
  player_id  uuid REFERENCES players(id) ON DELETE CASCADE NOT NULL,
  team_id    uuid REFERENCES teams(id) ON DELETE CASCADE NOT NULL,
  points     int DEFAULT 0,
  created_at timestamptz DEFAULT now(),
  UNIQUE(fixture_id, player_id)
);

CREATE INDEX IF NOT EXISTS idx_players_team   ON players(team_id);
CREATE INDEX IF NOT EXISTS idx_pstats_fixture ON player_stats(fixture_id);
CREATE INDEX IF NOT EXISTS idx_pstats_player  ON player_stats(player_id);
CREATE INDEX IF NOT EXISTS idx_pstats_team    ON player_stats(team_id);

-- ----------------------------------------------------------------
-- RLS
-- ----------------------------------------------------------------
ALTER TABLE players      ENABLE ROW LEVEL SECURITY;
ALTER TABLE player_stats ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='players' AND policyname='Public read players') THEN
    CREATE POLICY "Public read players" ON players FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='player_stats' AND policyname='Public read player_stats') THEN
    CREATE POLICY "Public read player_stats" ON player_stats FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='players' AND policyname='Admin write players') THEN
    CREATE POLICY "Admin write players" ON players
      FOR ALL USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename='player_stats' AND policyname='Admin write player_stats') THEN
    CREATE POLICY "Admin write player_stats" ON player_stats
      FOR ALL USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL);
  END IF;
END $$;

